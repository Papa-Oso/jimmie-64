"""Pin the explicitly identified private unified candidate without staging live files.

Verify every engine-loaded file against the frozen baseline plus the candidate's
six-file bundle. Only the two existing data mailboxes retain dynamic validation.
"""
from pathlib import Path
import argparse
import hashlib
import json
from stage_jimmie_companion import engine_file
from pin_jimmie_text_profile import REVIEWED_SHA

ROOT = Path(__file__).resolve().parents[1]
LIVE = ROOT.parent / 'jimmie-64'
DYNAMIC = {'director_relay.lua': 1, 'route_launch_profile.lua': 2}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require(condition, message):
    if not condition:
        raise SystemExit(message)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=LIVE / 'docs/unified-launch-20261107/integrated-candidate.json')
    parser.add_argument('--expected-manifest-sha256', required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    require(sha(args.manifest) == args.expected_manifest_sha256, 'Candidate manifest changed; review the new identity first.')
    candidate = json.loads(args.manifest.read_text(encoding='utf-8'))
    source = Path(candidate['mod_source'])
    expected = LIVE / 'docs/unified-launch-20261107/candidate/coopdx/sm64coopdx/mods/jimmie'
    require(source.resolve() == expected.resolve(), 'Only the designated private candidate is accepted.')
    baseline_path = ROOT / 'build/integrated-preview/source-manifest.json'
    baseline = {e['path']: e for e in json.loads(baseline_path.read_text(encoding='utf-8'))['files']}
    bundle_path = Path(candidate['bundle_path'])
    require(sha(bundle_path) == candidate['bundle_sha256'], 'Candidate source bundle changed.')
    bundle = json.loads(bundle_path.read_text(encoding='utf-8'))['files']
    changes = candidate['changes']
    require(set(bundle) == set(changes), 'Bundle and candidate change inventories disagree.')
    for name, change in changes.items():
        require(name not in DYNAMIC, 'Changing dynamic mailbox policy is outside this pin update.')
        require(change['before_sha256'] == baseline.get(name, {}).get('sha256'), f'Baseline mismatch: {name}')
        require(change['after_sha256'] == bundle[name]['sha256'], f'Bundle identity mismatch: {name}')
        require(sha(LIVE / bundle[name]['path']) == change['after_sha256'], f'Bundle source changed: {name}')
    files = sorted(p.relative_to(source) for p in source.rglob('*') if p.is_file() and engine_file(p.relative_to(source)))
    require({p.as_posix() for p in files} == set(baseline) | set(changes), 'Unexpected missing or extra candidate files.')
    entries = []
    for rel in files:
        data = (source / rel).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        name = rel.as_posix()
        if name not in DYNAMIC:
            wanted = changes[name]['after_sha256'] if name in changes else baseline[name]['sha256']
            require(digest == wanted, f'Candidate source changed: {name}')
        entries.append(dict(path=name, sha256=digest, md5=hashlib.md5(data).hexdigest(), dynamic=DYNAMIC.get(name, 0)))
    text_source = source.parent / 'jimmie_text'
    require(sorted(p.relative_to(text_source).as_posix() for p in text_source.rglob('*') if p.is_file()) == ['main.lua'],
            'Candidate text inventory changed.')
    require(sha(text_source / 'main.lua') == REVIEWED_SHA == candidate['jimmie_text_sha256'], 'Candidate text source changed.')
    header = ('/* Private unified candidate; exact manifest SHA-256: ' + args.expected_manifest_sha256 + '\n'
              ' * Generated by tools/pin_jimmie_candidate_profile.py. Engine MD5 identity, not anti-cheat. */\n'
              'static const struct JimmieProfileFile sProfileFiles[] = {\n')
    for entry in entries:
        values = ','.join('0x' + entry['md5'][i:i+2] for i in range(0, 32, 2))
        header += '    {' + json.dumps(entry['path']) + ', {' + values + '}, ' + str(entry['dynamic']) + '},\n'
    header += '};\n'
    target = ROOT / 'src/pc/generated/jimmie_companion_profile.inc.h'
    report_path = ROOT / 'build/unified-candidate-profile.json'
    report = dict(source=str(source), candidate_manifest=str(args.manifest), candidate_manifest_sha256=args.expected_manifest_sha256,
                  baseline_manifest_sha256=sha(baseline_path), bundle_sha256=candidate['bundle_sha256'],
                  source_main_sha256=sha(source / 'main.lua'), text_sha256=REVIEWED_SHA, files=entries,
                  loaded_files=len(entries), lua_files=sum(e['path'].endswith('.lua') for e in entries),
                  dynamic_files=DYNAMIC, changes=changes,
                  limits='Exact candidate identity only; movement acceptance and full-run timing remain separate.')
    if args.check:
        require(target.read_text(encoding='utf-8') == header, 'Generated native profile does not match the candidate.')
    else:
        target.write_text(header, encoding='utf-8', newline='\n')
        report_path.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(dict(source=str(source), manifest_sha256=args.expected_manifest_sha256,
                         files=len(entries), lua_files=report['lua_files'], check_only=args.check)))


if __name__ == '__main__':
    main()
