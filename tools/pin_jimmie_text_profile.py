"""Pin only the reviewed presentation-only text mod; never edit the live source.

Changing REVIEWED_SHA requires another source review, not automatic acceptance.
The engine uses MD5 cache identities; SHA-256 records the reviewed exact bytes.
"""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
REVIEWED_SHA = '8f652921d2610c2cb607a2397d73c3402d7b2d414d04bdefa47ec344411000ca'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT.parent / 'jimmie-64/coopdx/sm64coopdx/mods/jimmie_text')
    parser.add_argument('--check', action='store_true', help='Verify source and generated header without writing.')
    args = parser.parse_args()
    files = sorted(p.relative_to(args.source).as_posix() for p in args.source.rglob('*') if p.is_file())
    if files != ['main.lua']:
        raise SystemExit('Text source inventory changed: review before pinning.')
    data = (args.source / 'main.lua').read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != REVIEWED_SHA:
        raise SystemExit('Text source hash changed: review before pinning.')
    md5 = hashlib.md5(data).hexdigest()
    values = ','.join('0x' + md5[i:i+2] for i in range(0, 32, 2))
    header = ('/* Reviewed presentation-only jimmie_text/main.lua.\n'
              f' * SHA-256: {REVIEWED_SHA}\n'
              ' * Generated by tools/pin_jimmie_text_profile.py; engine MD5 identity, not anti-cheat. */\n'
              'static const struct JimmieProfileFile sTextProfileFiles[] = {\n'
              f'    {{"main.lua", {{{values}}}, 0}},\n'
              '};\n')
    target = ROOT / 'src/pc/generated/jimmie_text_profile.inc.h'
    if args.check:
        if target.read_text(encoding='utf-8') != header:
            raise SystemExit('Generated text profile does not match the reviewed source.')
    else:
        target.write_text(header, encoding='utf-8', newline='\n')
    print(json.dumps(dict(source=str(args.source), sha256=digest, md5=md5,
                         bytes=len(data), files=files, check_only=args.check)))


if __name__ == '__main__':
    main()
