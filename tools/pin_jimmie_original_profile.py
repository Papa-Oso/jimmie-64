"""Pin current original companion sources plus verified native-generated actors."""
from pathlib import Path
import argparse, hashlib, json, shutil, importlib.util
ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('profile_file_rules',ROOT/'tools/stage_jimmie_companion.py')
rules=importlib.util.module_from_spec(spec);spec.loader.exec_module(rules)
engine_file=rules.engine_file
ACTORS={'jimmie_orig_board_geo.bin','jimmie_orig_rg_geo.bin','jimmie_orig_tee_geo.bin','jimmie_orig_vest_geo.bin','jimmie_original_brace_geo.bin'}
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--run',type=Path,required=True);p.add_argument('--check',action='store_true');a=p.parse_args()
 run=a.run.resolve();source=ROOT/'mods/jimmie';cache=run/'game/mods/jimmie/actors'
 if not run.is_relative_to(ROOT/'build/jimmie-runs'):raise SystemExit('Only this fork isolated runs are accepted')
 inputs=json.loads((run/'input.json').read_text());result=json.loads((run/'report.json').read_text())
 if not result['checks'].get('five_original_actors'):raise SystemExit('Run did not load all five original actors')
 files=list(cache.glob('*.bin'))
 if {f.name for f in files}!=ACTORS:raise SystemExit('Unexpected actor inventory; no legacy poses allowed')
 for name,digest in inputs['package_files'].items():
  if name.startswith('actors/') and sha(source/name)!=digest:raise SystemExit('Actor source changed: '+name)
 for f in files:
  if sha(f)!=result['actor_caches'][f.name]['sha256']:raise SystemExit('Runtime cache changed: '+f.name)
 entries=[]
 for f in sorted(source.rglob('*')):
  if f.is_file() and engine_file(f.relative_to(source)):
   rel=f.relative_to(source).as_posix();data=f.read_bytes()
   if rel.startswith('actors/'):raise SystemExit('Generated actors belong in build output, not source inventory')
   if rel in ('director_relay.lua','route_launch_profile.lua'):raise SystemExit('Dynamic mailbox port requires explicit review')
   entries.append({'path':rel,'sha256':sha(f),'md5':hashlib.md5(data).hexdigest(),'dynamic':0})
 for f in files:
  entries.append({'path':'actors/'+f.name,'sha256':sha(f),'md5':hashlib.md5(f.read_bytes()).hexdigest(),'dynamic':0})
 entries.sort(key=lambda e:e['path'])
 header='/* Original articulated native fork candidate. Generated by tools/pin_jimmie_original_profile.py.\n * Engine MD5 identities, not anti-cheat or asset-rights certification. */\nstatic const struct JimmieProfileFile sProfileFiles[] = {\n'
 for e in entries:
  values=','.join('0x'+e['md5'][i:i+2] for i in range(0,32,2))
  header+='    {'+json.dumps(e['path'])+', {'+values+'}, 0},\n'
 header+='};\n'
 target=ROOT/'src/pc/generated/jimmie_companion_profile.inc.h'
 if a.check:
  if target.read_text()!=header:raise SystemExit('Profile differs from reviewed source/cache inputs')
 else:
  out=ROOT/'build/jimmie-runtime-assets/actors';out.mkdir(parents=True,exist_ok=True)
  existing={f.name for f in out.iterdir() if f.is_file()}
  if existing-ACTORS:raise SystemExit('Unexpected existing generated actor; no deletion attempted')
  target.write_text(header,encoding='utf-8',newline='\n')
  for f in files:shutil.copyfile(f,out/f.name)
  report={'schema':1,'header_sha256':sha(target),'source_main_sha256':sha(source/'main.lua'),
   'actor_generation_run':str(run.relative_to(ROOT)),'actor_generation_engine_sha256':inputs['engine_sha256'],
   'source_run_overall_passed':result['passed'],'source_run_limits':result['limits'],'files':entries,
   'loaded_files':len(entries),'actor_files':5,'dynamic_mailboxes':False,
   'limits':'Pins exact source and five independently authored actor caches. Requires new-engine profile acceptance check; no full-run or rights clearance.'}
  (ROOT/'docs/jimmie/integration/original-profile.json').write_text(json.dumps(report,indent=2)+'\n')
 print(json.dumps({'files':len(entries),'actors':5,'header_sha256':sha(target),'check_only':a.check}))
if __name__=='__main__':main()
