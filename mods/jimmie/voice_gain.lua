function M.volume(name, volume)
    local v = tonumber(volume)
    if v == nil then v = 1 end
    if v ~= v or v == math.huge or v == -math.huge then return 0 end
    v = math.max(0, v)
    if not M.enabled then return v end
    local cap = caps[name]
    if not cap then return v end -- unknown/unmeasured recordings get no boost
    return math.min(v * 10^(M.gainDb/20), cap)
end
return M
